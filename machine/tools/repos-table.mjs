/**
 * repos-table.mjs — the tables of SYS-013 (the repositories, as wired),
 * generated from system/repos.yaml.
 *
 * THE PROBLEM THIS SOLVES
 * -----------------------
 * SYS-013 held the map of the organisation's repositories as a hand-written
 * Markdown table: what each repository is, who owns it, its licence, what
 * reads it. Two repositories were renamed on 2026-11-05 and a third archived;
 * the table said nothing of it, because nothing read the table back. Hermes
 * kept a second list of its own (repos_numen.py) with the same names and ids.
 * Three copies of one fact.
 *
 * So the map is DATA — one entry per repository in system/repos.yaml, keyed by
 * GitHub's numeric id, which a rename keeps — and SYS-013 keeps the prose
 * (why, how a shared thing flows, the copies that are debt). The tables inside
 * the markers are generated, and --check exits 1 when they differ from the
 * data. The shape is rule-index.mjs's:
 *
 *   node machine/tools/repos-table.mjs            # rewrite the block in SYS-013
 *   node machine/tools/repos-table.mjs --check    # exit 1 if it has drifted
 *   node machine/tools/repos-table.mjs --print    # the block, to stdout
 *   node machine/tools/repos-table.mjs --json     # the entries, parsed, to stdout
 *
 * WHY A SMALL READER AND NOT A YAML LIBRARY
 * -----------------------------------------
 * Tools and guards run in CI before any dependency is installed (see
 * machine/scripts/lib/frontmatter.mjs). The data is one list of flat mappings,
 * so the reader takes exactly that subset and refuses anything else with the
 * line number, rather than guessing. The test compares it with js-yaml
 * whenever web/node_modules has it.
 *
 * "Read by" is not stored. It is the other repositories' `reads`, turned
 * round, so the two directions cannot disagree.
 *
 * WHAT THIS TOOL DOES NOT CHECK (D-025 — declare your blindness):
 * see machine/scripts/blind-spots.json, entry "repos-table".
 */
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { ROOT } from '../scripts/lib/frontmatter.mjs';
import { declareBlindSpots } from '../scripts/lib/blindness.mjs';

export const BEGIN = '<!-- repos-table:begin — generated by machine/tools/repos-table.mjs from system/repos.yaml; do not edit by hand -->';
export const END = '<!-- repos-table:end -->';

export const DATA = 'system/repos.yaml';
export const TARGET = 'system/SYS-013-the-repositories-as-wired.md';
export const STATES = ['active', 'deprecated', 'to-archive', 'archived', 'to-create'];

/* ---------- the reader ---------- */

/** One value written after `key:` on its line (or inside a block list). */
function value(raw, at) {
  const s = raw.trim();
  if (s.startsWith('"')) {
    if (!/^"(?:[^"\\]|\\.)*"$/.test(s)) throw new Error(`${DATA}:${at}: a quoted string must end at the closing quote, with nothing after it`);
    return JSON.parse(s);
  }
  if (s === 'null') return null;
  if (s === '[]') return [];
  if (/^-?\d+$/.test(s)) return Number(s);
  if (/^[["'{&*!|>%@`]/.test(s) || /:\s/.test(s) || /\s#/.test(s) || s === '')
    throw new Error(`${DATA}:${at}: write "${s.slice(0, 30)}…" in double quotes`);
  return s;
}

/** The entries of `repositories:`, in file order. */
export function parseRepos(text) {
  const out = [];
  let cur = null;
  let list = null;
  let root = false;
  text.split('\n').forEach((line, n) => {
    const at = n + 1;
    if (!line.trim() || /^\s*#/.test(line)) return;
    if (/^repositories:\s*$/.test(line)) { root = true; return; }
    if (!root) throw new Error(`${DATA}:${at}: expected "repositories:" first`);
    let m = /^ {2}- ([a-z_]+):(?: (.*))?$/.exec(line);
    if (m) { cur = {}; out.push(cur); list = null; }
    else m = /^ {4}([a-z_]+):(?: (.*))?$/.exec(line);
    if (m) {
      if (!cur) throw new Error(`${DATA}:${at}: a key outside an entry`);
      if (Object.hasOwn(cur, m[1])) throw new Error(`${DATA}:${at}: "${m[1]}" is written twice in one entry`);
      if (m[2] === undefined) { cur[m[1]] = []; list = cur[m[1]]; } else { cur[m[1]] = value(m[2], at); list = null; }
      return;
    }
    m = /^ {6}- (.*)$/.exec(line);
    if (m && list) { list.push(value(m[1], at)); return; }
    throw new Error(`${DATA}:${at}: not a line this reader takes (a list of flat mappings under "repositories:"): ${line.trim().slice(0, 50)}`);
  });
  return out;
}

export function loadRepos(root = ROOT) {
  return parseRepos(readFileSync(path.join(root, DATA), 'utf8'));
}

/* ---------- the tables ---------- */

export const cell = (s) => String(s).replace(/\|/g, '\\|').replace(/\s*\n\s*/g, ' ').trim();
const or = (s, dash = '—') => (s === null || s === undefined || s === '' ? dash : cell(s));

/** "repo: what" → ["repo", "what"]. */
const edge = (e) => { const i = e.indexOf(': '); return [e.slice(0, i), e.slice(i + 2)]; };

function nameCell(r) {
  const was = r.former_names?.length ? ` (was ${r.former_names.join(', ')})` : '';
  return `**${r.name}**${was}`;
}

export function buildBlock(repos) {
  const readBy = new Map(repos.map((r) => [r.name, []]));
  for (const r of repos) {
    for (const e of r.reads ?? []) {
      const [to, what] = edge(e);
      readBy.get(to)?.push(`${r.name} (${what})`);
    }
  }

  const first = [
    '| Repository | State | Project · board | Owner | What it is | What it is not | Licence regime |',
    '|---|---|---|---|---|---|---|',
    ...repos.map((r) => {
      const where = r.project && r.board ? `${r.project} · ${r.board}` : or(r.project ?? r.board);
      return `| ${nameCell(r)} | ${r.state} | ${cell(where)} | ${cell(r.owner)} | ${cell(r.is)} | ${cell(r.is_not)} | ${cell(r.licence)} |`;
    }),
  ];
  const second = [
    '| Repository | GitHub id | Address | Publishes | Reads | Read by |',
    '|---|---|---|---|---|---|',
    ...repos.map((r) => {
      const reads = (r.reads ?? []).map((e) => { const [to, what] = edge(e); return `${to} (${what})`; });
      return `| ${nameCell(r)} | ${r.id === null ? 'not yet' : r.id} | ${or(r.homepage)} | ${or(r.publishes)} | ${reads.length ? cell(reads.join('; ')) : '—'} | ${readBy.get(r.name).length ? cell(readBy.get(r.name).join('; ')) : '—'} |`;
    }),
  ];
  const counts = STATES.map((s) => [s, repos.filter((r) => r.state === s).length]).filter(([, n]) => n);
  const foot = `${repos.length} repositories: ${counts.map(([s, n]) => `${n} ${s}`).join(', ')}. Generated from \`${DATA}\`.`;

  return [
    BEGIN,
    '',
    ...first,
    '',
    'The lines between them. *Read by* is worked out from the *Reads* of the others, so the two directions cannot disagree.',
    '',
    ...second,
    '',
    foot,
    END,
  ].join('\n');
}

/** The document with its block replaced; null when the markers are missing. */
export function splice(doc, block) {
  const b = doc.indexOf(BEGIN);
  const e = doc.indexOf(END);
  if (b < 0 || e < b) return null;
  return doc.slice(0, b) + block + doc.slice(e + END.length);
}

/** The rows of a block, keyed by table and repository, for a drift report. */
function rowsOf(block) {
  const rows = new Map();
  let table = 0;
  for (const l of block.split('\n')) {
    if (l.startsWith('| Repository')) table++;
    const m = /^\| \*\*(.+?)\*\*/.exec(l);
    if (m) rows.set(`${table}:${m[1]}`, l);
  }
  return rows;
}

/* ---------- command line ---------- */

if (import.meta.url === `file://${process.argv[1]}`) {
  declareBlindSpots('repos-table');
  const argv = new Set(process.argv.slice(2));
  let repos;
  try { repos = loadRepos(); } catch (err) { console.error(`repos-table: ${err.message}`); process.exit(2); }

  if (argv.has('--json')) { console.log(JSON.stringify(repos, null, 2)); process.exit(0); }
  const block = buildBlock(repos);
  if (argv.has('--print')) { console.log(block); process.exit(0); }

  const file = path.join(ROOT, TARGET);
  const current = readFileSync(file, 'utf8');
  const wanted = splice(current, block);
  if (wanted === null) {
    console.error(`repos-table: ${TARGET} has no repos-table markers to hold the tables`);
    process.exit(2);
  }

  if (argv.has('--check')) {
    if (current === wanted) {
      console.log(`repos-table: ${TARGET} matches ${DATA} (${repos.length} repositories).`);
      process.exit(0);
    }
    const have = rowsOf(current.slice(current.indexOf(BEGIN), current.indexOf(END)));
    const want = rowsOf(block);
    const keys = [...new Set([...have.keys(), ...want.keys()])];
    const drift = keys.filter((k) => have.get(k) !== want.get(k));
    console.error(`repos-table: ${TARGET} has DRIFTED from ${DATA} — ${drift.length || 'no'} row(s) stale. The data is the source; the document is not.`);
    for (const k of drift) {
      const name = k.slice(k.indexOf(':') + 1);
      const which = k.startsWith('1:') ? 'first table' : 'second table';
      if (!have.has(k)) console.error(`  ${name}  missing from the ${which}`);
      else if (!want.has(k)) console.error(`  ${name}  in the ${which}, not in ${DATA}`);
      else console.error(`  ${name}  differs in the ${which}`);
    }
    console.error(`\nRegenerate it: node machine/tools/repos-table.mjs`);
    process.exit(1);
  }

  writeFileSync(file, wanted);
  console.log(`repos-table: ${TARGET} rewritten from ${DATA} — ${repos.length} repositories.`);
}
