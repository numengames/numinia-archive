// skill-catalogo.mjs — renders agents/skills/numinia-construir-3d/references/catalogo.md
// from the engine's library (biblioteca.json), so the page cannot drift from it.
//
//   node machine/tools/skill-catalogo.mjs --library <biblioteca.json>           # write the page
//   node machine/tools/skill-catalogo.mjs --library <biblioteca.json> --check   # exit 1 if the page is stale
//
// The library says which models exist and under what licence; it does not say
// how big they are. The sizes below were measured from the model files (the
// bounding box of the geometry at scale 1) and are the one hand-kept part.
// A model with no measured size is printed as «not measured», never guessed.
import { createHash } from 'node:crypto';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
export const PAGE = 'agents/skills/numinia-construir-3d/references/catalogo.md';

/** Measured from the model files: width × height × depth in metres at scale 1, and what it is for. */
export const MEASURED = {
  bloque: { size: '1 × 1 × 1 m', use: 'a plain cube resting on the ground; scale it into tables, benches, walls, steps, columns' },
  farolillo: { size: '0.17 × 0.31 × 0.17 m', use: 'a small brass lantern that glows; for a table, a post or the ground' },
  loma: { size: '20 × 2 × 20 m', use: 'a low hill of terrain, centred on its point, 2 m high at the top' },
  robot: { size: '6.6 × 5.2 × 3.2 m (from the file, not seen in a world)', use: 'a toy robot, decoration; scale it down (about 0.3) to a person’s size' },
};

// Written in pieces so that this script's own licence (MIT, above) is the only tag a scanner finds in it.
const TAGS = ['SPDX-' + 'FileCopyrightText: 2026 Numen Games S.L.', 'SPDX-' + 'License-Identifier: CC0-1.0'].join('\n');

const OWN = /obra propia|own work/i;

/** The page, as text, for a library and the sha256 of its file. */
export function renderCatalogo(library, libraryHash) {
  const rows = library.modelos.map((m) => {
    if (m.licencia !== 'CC0-1.0' && !OWN.test(String(m.autor))) {
      throw new Error(`model «${m.id}»: only CC0 or own work may be placed (licence ${m.licencia}, author ${m.autor})`);
    }
    const k = MEASURED[m.id];
    return `| \`${m.id}\` | ${m.nombre} | ${k ? k.size : 'not measured'} | ${k ? k.use : '—'} | ${m.licencia} · ${m.autor} |`;
  });
  return `---
title: "SKILL reference — What you may place"
type: agent
status: active
version: "1.0.0"
created: "2026-10-20T15:00:00+02:00"
updated: "2026-10-20T15:00:00+02:00"
author: "ursa"
owner: "oracle"
section: "People and culture"
tags: [agents, skill, reference, catalogue]
license: "CC0-1.0"
registration: exempt
registration_reason: "a reference file of a cross-agent skill is identified by its path inside the skill folder (ADR-005)"
---

<!--
${TAGS}
-->

# What you may place

Generated by \`machine/tools/skill-catalogo.mjs\` from the engine's library (biblioteca.json, sha256 ${libraryHash.slice(0, 12)}…). Do not edit by hand. In a world, \`mirar\` lists the models you may place now; trust it over this page.

All sizes are width × height × depth at \`escala\` 1. Every model's origin is the centre of its base, so \`y\` is where its bottom rests.

| id | Name | Size | For | Licence · author |
|---|---|---|---|---|
${rows.join('\n')}

\`escala\` goes from 0.1 to 10 on each axis (\`escala_x\` width, \`escala_y\` height, \`escala_z\` depth), so a thin piece cannot be thinner than 10 cm.

## Next

- \`guia recetas\` — put these together: table, doorway, steps, small square.
`;
}

function main() {
  const args = process.argv.slice(2);
  const at = args.indexOf('--library');
  if (at < 0 || !args[at + 1]) {
    console.error('usage: skill-catalogo.mjs --library <biblioteca.json> [--check]');
    process.exit(2);
  }
  const raw = readFileSync(args[at + 1]);
  const text = renderCatalogo(JSON.parse(raw.toString('utf-8')), createHash('sha256').update(raw).digest('hex'));
  const file = path.join(ROOT, PAGE);
  if (args.includes('--check')) {
    if (!existsSync(file) || readFileSync(file, 'utf-8') !== text) {
      console.error(`${PAGE} is not what the library renders: run the script without --check`);
      process.exit(1);
    }
    console.log(`${PAGE} matches the library.`);
    return;
  }
  writeFileSync(file, text);
  console.log(`wrote ${PAGE}`);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) main();
